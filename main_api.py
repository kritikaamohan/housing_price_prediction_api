import nest_asyncio
import uvicorn
import threading
from pyngrok import ngrok

nest_asyncio.apply()

public_url = ngrok.connect(8000)
print("Your API is live at:", public_url)

def run():
    uvicorn.run("main:app", host="0.0.0.0", port=8000)

thread = threading.Thread(target=run)
thread.start()